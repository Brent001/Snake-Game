_CACHE = {}


def glyph_runs(ch):
    """Runs (x, y, width) of one glyph plus its width."""
    rows = _G.get(ch, _G["?"])
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                x2 = x
                while x2 + 1 < len(row) and row[x2 + 1] == "#":
                    x2 += 1
                out.append((x, y, x2 - x + 1))
                x = x2 + 1
            else:
                x += 1
    return out, len(rows[0])


def compile_text(text):
    """-> (list of (char_index, x, y, w) runs in glyph units, total width in glyph units)."""
    text = text.upper()
    hit = _CACHE.get(text)
    if hit:
        return hit
    runs, x = [], 0
    for i, ch in enumerate(text):
        gr, w = glyph_runs(ch)
        for gx, gy, gw in gr:
            runs.append((i, x + gx, gy, gw))
        x += w + 1
    res = (runs, max(0, x - 1))
    _CACHE[text] = res
    return res


def text_width(text, scale):
    return compile_text(text)[1] * scale
